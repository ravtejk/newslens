"""GENERATED ASSETS FOR THE HOSTED READER — the palette crosses the tree line once.

NL-163 Stage-A, milestone 2. Chartered by the engineering adjudication of
2026-08-29 §Q2: "the tokens/login shell are GENERATED from webui.TOKENS by a
product-tree script and drift-pinned by a suite test (a generated,
header-marked artifact is consumption, not a copy)."

WHY THIS MODULE EXISTS
----------------------
`hosted/` is a separate deployable with its own dependency story: it must not
import `newslens`, and its Docker image does not carry the product tree. So the
paper's palette has to reach it somehow, and there are exactly two ways: a
second table of hexes (drift, forbidden by DESIGN_SYSTEM.md), or a generated
artifact whose source is `webui.TOKENS` and whose staleness is a red test.

Everything this module emits is therefore DERIVED:

  * `tokens.css`        — webui.TOKENS verbatim + the shipped `body.dark`
                          inversion, both lifted out of webui by the same
                          extractor the bundle uses. The hosted shell's own CSS
                          then names nothing but `var(--…)`.
  * `manifest.webmanifest` — `background_color`/`theme_color` READ from the
                          token block. A manifest cannot hold a `var()`, so
                          this is one of the two places a hex must be spelled;
                          it is spelled by a program that read the source.
  * the icon C PNGs     — the principal's pick (DECISIONS 2026-08-29: "Icon =
                          C, the evening plate"), drawn from the same three
                          token values: ink ground, paper serif N, terra
                          underline. Rendered here rather than pasted in as
                          opaque bytes so the icon has provenance a reviewer
                          can re-run, and so a palette re-pin reaches the home
                          screen like it reaches everything else.

STDLIB ONLY (the product tree's three-dependency law): the PNG encoder is
`zlib` + `struct`, and the rasteriser below is ~80 lines of scanline coverage.
No image library, no font file, no network — `scripts/gen-hosted-assets`
reproduces every byte on a fresh clone.
"""

from __future__ import annotations

