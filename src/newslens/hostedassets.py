def render_boot_js() -> str:
    """The bundle's OWN boot script, shared with the shell pages.

    M1 gate, FIX-2's landing note: "M2's shell inherits BOOT_JS wholesale."
    The shell states (login, no-edition, archive) must resolve dark mode before
    first paint by the same three-state rule as an edition, and must carry the
    same touch-gated Dynamic Type seed — a second implementation would be a
    second dark-mode bug waiting to be found on one surface only."""
    from .editionbundle import BOOT_JS
    return (f"/* {GENERATED_MARKER} — DO NOT EDIT BY HAND.\n"
            "   Source: src/newslens/editionbundle.py (BOOT_JS), the same\n"
            "   script the frozen edition carries. Regenerate:\n"
            "   scripts/gen-hosted-assets */\n" + BOOT_JS.strip() + "\n")


def generated_assets() -> Dict[str, bytes]:
    out: Dict[str, bytes] = {
        "static/tokens.css": render_tokens_css().encode("utf-8"),
        "static/boot.js": render_boot_js().encode("utf-8"),
        "static/manifest.webmanifest": render_manifest().encode("utf-8"),
    }
    for size in (192, 512):
        out[f"static/icon-{size}.png"] = render_icon(size)
        out[f"static/icon-maskable-{size}.png"] = render_icon(size, maskable=True)
    # iOS ignores the manifest's icons for the home screen and reads this one.
    out["static/apple-touch-icon.png"] = render_icon(180)
    out["static/favicon.png"] = render_icon(48)
    return out


def stale_assets(root: Path = None) -> List[str]:
    """Generated files whose bytes on disk are not what this module produces."""
    base = hosted_dir(root)
    stale = []
    for rel, data in generated_assets().items():
        path = base / rel
        try:
            if path.read_bytes() != data:
                stale.append(rel)
        except OSError:
            stale.append(rel)
    return stale


def write_assets(root: Path = None) -> List[Tuple[str, bool]]:
    """Write every generated asset. Returns (path, changed) per file."""
    base = hosted_dir(root)
    written = []
    for rel, data in generated_assets().items():
        path = base / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        changed = True
        try:
            changed = path.read_bytes() != data
        except OSError:
            pass
        if changed:
            path.write_bytes(data)
        written.append((rel, changed))
    return written


def main(argv=None) -> int:
    paths.allow_real_paths()
    written = write_assets()
    for rel, changed in written:
        print(f"  {'wrote  ' if changed else 'current'} hosted/{rel}")
    n = sum(1 for _, changed in written if changed)
    print(f"{len(written)} generated assets · {n} changed · source: webui.TOKENS")
    return 0
